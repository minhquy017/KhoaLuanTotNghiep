class I18nManager {
  constructor() {
    this.currentLang = this.getInitialLang();
  }

  getLanguage() {
    return this.currentLang;
  }

  getInitialLang() {
    try {
      const saved = localStorage.getItem('hue_lang');
      if (saved === 'en' || saved === 'vi') return saved;
      const navLang = navigator.language || '';
      return navLang.toLowerCase().startsWith('en') ? 'en' : 'vi';
    } catch {
      return 'vi';
    }
  }

  t(key, fallback = '') {
    const dict = translations[this.currentLang] || translations.vi;
    if (dict[key] !== undefined) return dict[key];
    const viDict = translations.vi;
    return viDict[key] !== undefined ? viDict[key] : (fallback || key);
  }

  setLanguage(lang) {
    if (lang !== 'vi' && lang !== 'en') return;
    this.currentLang = lang;
    try {
      localStorage.setItem('hue_lang', lang);
    } catch { }

    document.documentElement.setAttribute('lang', lang);

    // Update document title
    document.title = this.t('appDocTitle', 'Du lịch Cố đô Huế');

    // Update all static HTML elements with translation attributes
    this.updateDomTranslations();

    // Dispatch global event for reactive components (weather, map, auth, budget, chat)
    window.dispatchEvent(new CustomEvent('hue:language-change', { detail: { lang } }));
  }

  toggleLanguage() {
    const nextLang = this.currentLang === 'vi' ? 'en' : 'vi';
    this.setLanguage(nextLang);
    return nextLang;
  }

  updateDomTranslations() {
    const lang = this.currentLang;
    const dict = translations[lang] || translations.vi;

    // 0. Update document title
    if (dict.appDocTitle) {
      document.title = dict.appDocTitle;
    }

    // 1. Translate innerText / textContent
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        el.textContent = dict[key];
      }
    });

    // 2. Translate placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key] !== undefined) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // 3. Translate title / aria-label
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key] !== undefined) {
        el.setAttribute('title', dict[key]);
        if (el.hasAttribute('aria-label')) {
          el.setAttribute('aria-label', dict[key]);
        }
      }
    });

    // 4. Translate data-tooltip
    document.querySelectorAll('[data-i18n-tooltip]').forEach(el => {
      const key = el.getAttribute('data-i18n-tooltip');
      if (dict[key] !== undefined) {
        el.setAttribute('data-tooltip', dict[key]);
        if (!el.hasAttribute('data-i18n-title')) {
          el.setAttribute('title', dict[key]);
        }
      }
    });

    // 5. Translate aria-label explicitly
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const key = el.getAttribute('data-i18n-aria');
      if (dict[key] !== undefined) {
        el.setAttribute('aria-label', dict[key]);
      }
    });

    // 6. Update active state on language switcher pills
    document.querySelectorAll('.lang-btn').forEach(btn => {
      const btnLang = btn.getAttribute('data-lang');
      btn.classList.toggle('active', btnLang === lang);
    });
  }
}

export const i18n = new I18nManager();
window.i18n = i18n;
